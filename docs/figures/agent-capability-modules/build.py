# ── 模塊頁的共用版型 ───────────────────────────────────────────────
def modules_page(mods, lines, aria, y0=34):
    s = []
    n = len(mods)
    h = 78 if n >= 4 else 96
    T(s, 20, 24, "模塊　用在哪", cls="tx-lbl", fill=MOD)
    T(s, 180, 24, "規格（建立什麼性質；不講機制）", cls="tx-lbl", fill=INK2)
    T(s, 572, 24, "進出　沙盒怎麼驗", cls="tx-lbl", fill=GOAL)
    for i, (name, used, main, sub, io, verify) in enumerate(mods):
        y = y0 + i * h
        rect(s, 20, y + 6, 3, h - 18, col=MOD, fill=MOD, sw=0)
        T(s, 34, y + 24, name, cls="tx", fill=MOD, w=700)
        for k, u in enumerate(used.split("|")):
            T(s, 34, y + 42 + 16 * k, u, fill=GRAY)
        yy = y + 24
        for c in main:
            T(s, 180, yy, c, cls="tx", fill=INK2)
            yy += 18
        for c in sub:
            T(s, 180, yy - 2, c, cls="tx-s", fill=INK2)
            yy += 16
        T(s, 572, y + 24, io, fill=INK2)
        T(s, 572, y + 42, "沙盒：" + verify, fill=GOAL)
        line(s, 20, y + h - 6, 860, y + h - 6)
    bottom(s, y0 + n * h + 8, lines)
    return svg(s, 880, 480, aria)


